/* =====================================================
   CATEGORY PAGE
===================================================== */

document.addEventListener("DOMContentLoaded", () => {

  const params =
    new URLSearchParams(window.location.search);

  const category =
    params.get("category") || "oils";


  const titleElement =
    document.getElementById("categoryTitle");

  const descriptionElement =
    document.getElementById("categoryDescription");

  const countElement =
    document.getElementById("categoryCount");

  const breadcrumbElement =
    document.getElementById("breadcrumbCategory");

  const productsCountElement =
    document.getElementById("productsCount");

  const grid =
    document.getElementById("productsGrid");


  /* ================= CATEGORY PAGE CHECK ================= */

  if (
    !titleElement ||
    !descriptionElement ||
    !countElement ||
    !breadcrumbElement ||
    !productsCountElement ||
    !grid
  ) {
    return;
  }


  /* ================= CATEGORY DATA ================= */

  const categoryInfo = {

    oils: {
      title: "🫒 روغن‌ها",
      description:
        "مجموعه روغن‌های طبیعی و خالص کاژان.",
    },

    tea: {
      title: "🍵 چای و دمنوش",
      description:
        "انواع چای و دمنوش‌های متنوع نوش‌آیین.",
    },

    coffee: {
      title: "☕🍫 پودر قهوه و شکلات",
      description:
        "قهوه فوری، کافی میکس و انواع هات چاکلت.",
    },

    featured: {
      title: "🌿 محصولات منتخب",
      description:
        "محصولات منتخب نوش‌آیین.",
    }

  };


  const info =
    categoryInfo[category] ||
    categoryInfo.oils;


  const categoryProducts =
    window.products[category] || [];


  /* ================= PAGE TEXT ================= */

  titleElement.textContent =
    info.title;

  descriptionElement.textContent =
    info.description;

  countElement.textContent =
    `${categoryProducts.length} محصول`;

  breadcrumbElement.textContent =
    info.title;

  productsCountElement.textContent =
    `${categoryProducts.length} محصول`;


  /* ================= EMPTY ================= */

  if (categoryProducts.length === 0) {

    grid.innerHTML = `
      <div class="product-error">
        <div class="product-error-icon">
          🌿
        </div>

        <h2>
          محصولی پیدا نشد
        </h2>

        <p>
          محصولات این دسته هنوز اضافه نشده‌اند.
        </p>
      </div>
    `;

    return;
  }


  /* ================= RENDER PRODUCTS ================= */

  grid.innerHTML =
    categoryProducts
      .map(product => {

        const imagePath =
          `./images/${product.id}.jpg`;


        const unavailable =
          product.stock === 0;


        return `

          <article class="product-card">

            <a
              href="product.html?id=${encodeURIComponent(product.id)}"
              class="product-card-link"
            >

              <div
                class="product-card-image"
                style="
                  width:100%;
                  height:260px;
                  overflow:hidden;
                  border-radius:18px;
                  display:flex;
                  align-items:center;
                  justify-content:center;
                  background:#071D18;
                "
              >

                <img
                  src="${imagePath}"
                  alt="${product.name}"
                  style="
                    display:block;
                    width:100%;
                    height:100%;
                    object-fit:contain;
                    border-radius:18px;
                  "
                  onerror="
                    this.style.display='none';
                    this.parentElement.innerHTML=
                    '<div style=&quot;
                      font-size:55px;
                      display:flex;
                      align-items:center;
                      justify-content:center;
                      width:100%;
                      height:100%;
                    &quot;>
                      ${product.icon || "🌿"}
                    </div>';
                  "
                >

              </div>


              <div class="product-card-content">

                <div class="product-card-category">
                  ${product.category}
                </div>


                <h2 class="product-card-title">
                  ${product.name}
                </h2>


                ${
                  product.volume
                    ? `
                      <div class="product-card-volume">
                        ${product.volume}
                      </div>
                    `
                    : ""
                }


                <div class="product-card-bottom">

                  <div class="product-card-price">
                    ${Number(product.price).toLocaleString("fa-IR")}
                    تومان
                  </div>


                  <div
                    class="product-stock ${
                      unavailable
                        ? "out-of-stock"
                        : ""
                    }"
                  >
                    ${
                      unavailable
                        ? "ناموجود"
                        : "موجود"
                    }
                  </div>

                </div>

              </div>

            </a>

          </article>

        `;

      })
      .join("");


  /* ================= DOCUMENT TITLE ================= */

  document.title =
    `${info.title} | نوش‌آیین`;

});
